export function activationLabel(dept) {
  const rule = dept.activation || {};
  const parts = [];
  if (rule.always) parts.push('always active');
  if (rule.any?.length) parts.push(`tags: ${rule.any.join(', ')}`);
  if (rule.dimensions?.length) parts.push(`dimensions: ${rule.dimensions.join('/')}`);
  return parts.join(' · ');
}

export function charterMarkdown(dept, registry) {
  const division = registry.divisionById.get(dept.division);
  const ordered = [...dept.deliverables].sort(
    (a, b) => (registry.phaseById.get(a.phase)?.order || 99) - (registry.phaseById.get(b.phase)?.order || 99),
  );
  const lines = [
    '<!-- generated by studio/lib/generate.mjs — edit studio/registry/departments/*.json, then run: npm run studio -- gen -->',
    '',
    `# ${dept.id} — ${dept.name}`,
    '',
    `**Division:** ${division?.name || dept.division}`,
    `**Activation:** ${activationLabel(dept)}`,
    `**Queue:** \`studio/projects/<project>/queues/${dept.slug}.json\``,
    `**Memory:** \`studio/projects/<project>/memory/${dept.slug}.md\``,
    `**Deliverables:** \`studio/projects/<project>/deliverables/${dept.slug}/\``,
    '',
    '## System instructions',
    '',
    `You are the **${dept.name}** department of an autonomous game studio. ${dept.mission}`,
    '',
    'Operating rules:',
    '',
    '1. You are a specialist, not a generalist. Do your own work to production quality and refuse work that belongs to another department; name the department instead.',
    '2. Read the project specification, the shared knowledge documents relevant to your inputs, your working memory and your own queue before acting. Do not re-derive what is already recorded.',
    '3. Work one task at a time from your queue. State your assumptions in the artifact rather than blocking on questions you can resolve from the knowledge base.',
    '4. Every deliverable is a document at the artifact path below, written against every acceptance criterion. Evidence, numbers and commands belong in the document; unsupported claims do not.',
    '5. Write files, run commands and inspect assets yourself. Never claim a result you did not verify in this repository.',
    '6. If a task depends on another department, request it through the Studio Director and record the request in your memory; do not implement their system yourself.',
    '7. When your work changes an approved specification, say so explicitly in the Handoff section so the Director can record a decision.',
    '8. Finish by submitting for review. A deliverable is not done because you wrote it; it is done when the gate and the Director approve it.',
    '',
    '## Mission',
    '',
    dept.mission,
    '',
    '## Capabilities',
    '',
    ...dept.capabilities.map((capability) => `- ${capability}`),
    '',
    '## Deliverables',
    '',
    '| Deliverable | Phase | Artifact | Checks |',
    '| --- | --- | --- | --- |',
    ...ordered.map((deliverable) => {
      const checks = (deliverable.checks || []).join(', ') || '—';
      return `| ${deliverable.name} (\`${deliverable.id}\`) | ${registry.phaseById.get(deliverable.phase)?.name || deliverable.phase} | \`deliverables/${dept.slug}/${deliverable.id}.md\` | ${checks} |`;
    }),
    '',
    '### Acceptance criteria',
    '',
    ...ordered.flatMap((deliverable) => [
      `**${deliverable.name}** (\`${deliverable.id}\`)`,
      '',
      ...deliverable.acceptance.map((criterion) => `- ${criterion}`),
      '',
    ]),
    '## Quality gates',
    '',
    ...(dept.gates || ['Every acceptance criterion is met and evidenced.']).map((gate) => `- ${gate}`),
    '',
    'Automated gates also apply: every artifact needs front matter (`owner`, `department`, `revision`), the sections `Deliverable`, `Acceptance` and `Handoff`, at least 500 characters, and no `TBD` markers. Named checks must actually run and pass.',
    '',
    '## Inputs',
    '',
    ...(dept.inputs || []).map((input) => `- ${input}`),
    '',
    '## Handoff contract',
    '',
    `Consumers of this department's work: ${(dept.handoffs || []).map((id) => `**${id}** ${registry.byId.get(id)?.name || ''}`.trim()).join(', ') || 'none declared'}.`,
    '',
    `Department to consult when this work needs expertise you do not own: ${(dept.consults || []).map((id) => `**${id}** ${registry.byId.get(id)?.name || ''}`.trim()).join(', ') || 'the Studio Director'}.`,
    '',
    'A handoff must state: what was produced, where it lives, what the consumer must do with it, and what would make it invalid.',
    '',
    '## Working contract',
    '',
    '```bash',
    `npm run studio -- next <project> ${dept.id}          # pull the next ready task`,
    `npm run studio -- start <project> ${dept.id}-<deliverable>`,
    `npm run studio -- submit <project> ${dept.id}-<deliverable>`,
    `npm run studio -- prompt <project> ${dept.id}         # full instantiation prompt`,
    '```',
    '',
    'Artifact template: `studio/knowledge/templates/deliverable.md`. Copy it to the artifact path and fill every section.',
    '',
    '## Escalation',
    '',
    '- A missing dependency or unclear requirement: write the question in `memory` under "Open questions" and tell the Studio Director. Do not guess a new system into existence.',
    '- A conflict with an approved spec: raise it as a decision record, do not silently diverge.',
    '- A gate that cannot run on this machine: submit with `--skip <check> --reason "..."` so the skip is visible at review.',
    '',
  ];
  return `${lines.join('\n')}\n`;
}

export function departmentsIndexMarkdown(registry) {
  const lines = [
    '<!-- generated by studio/lib/generate.mjs — run: npm run studio -- gen -->',
    '',
    '# Department charters',
    '',
    `${registry.departments.length} departments across ${registry.divisions.length} divisions. Each charter is generated from \`studio/registry/departments/*.json\` and is the system prompt for that department's worker.`,
    '',
    '| ID | Department | Division | Activation | Charter |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const dept of registry.departments) {
    const division = registry.divisionById.get(dept.division);
    lines.push(`| ${dept.id} | ${dept.name} | ${division?.name || dept.division} | ${activationLabel(dept)} | [${dept.slug}.md](${dept.slug}.md) |`);
  }
  lines.push('');
  return `${lines.join('\n')}\n`;
}

export function roadmapMarkdown(project, registry) {
  const summary = phaseSummary(project, registry);
  const lines = [
    `# Roadmap — ${project.title}`,
    '',
    `\`${project.slug}\` · ${project.dimension.toUpperCase()} · ${project.platforms.join(', ')} · ${project.departments.length} departments active`,
    '',
    '| Phase | Lead | Tasks | Approved | In review | Blocked | Complete |',
    '| --- | --- | ---: | ---: | ---: | ---: | --- |',
  ];
  for (const phase of summary.filter((entry) => entry.active)) {
    const lead = registry.byId.get(phase.lead);
    lines.push(`| ${phase.order}. ${phase.name} | ${phase.lead} ${lead?.name || ''} | ${phase.tasks} | ${phase.approved} | ${phase.inReview} | ${phase.blocked} | ${phase.complete ? 'yes' : 'no'} |`);
  }
  lines.push('');

  for (const phase of summary.filter((entry) => entry.active)) {
    lines.push(`## ${phase.order}. ${phase.name}`, '');
    for (const task of project.tasks.filter((item) => item.phase === phase.id)) {
      const state = dependencyState(project, task);
      const suffix = task.status === 'approved' ? ' ✅' : task.status === 'in-review' ? ' 🔍' : task.status === 'blocked' ? ' ⛔' : state.ready ? ' ▶' : '';
      lines.push(`- [${task.id}](${task.artifact}) — ${task.name} (${task.dept})${suffix}`);
      if (task.waivedDeps?.length) {
        for (const waived of task.waivedDeps) lines.push(`  - dependency waived: ${waived.dependency} (${waived.reason})`);
      }
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

