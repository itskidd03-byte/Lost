export function statusMarkdown(project, registry) {
  const tasks = project.tasks || [];
  const counts = {
    queued: tasks.filter((task) => task.status === 'queued').length,
    active: tasks.filter((task) => task.status === 'active').length,
    inReview: tasks.filter((task) => task.status === 'in-review').length,
    approved: tasks.filter((task) => task.status === 'approved').length,
    rejected: tasks.filter((task) => task.status === 'rejected').length,
    blocked: tasks.filter((task) => task.status === 'blocked').length,
  };
  const phases = phaseSummary(project, registry).filter((phase) => phase.active);
  const current = phases.find((phase) => !phase.complete);
  const blocked = tasks.filter((task) => task.blockedReason);
  const rejected = tasks.filter((task) => task.status === 'rejected');
  const awaiting = tasks.filter((task) => task.status === 'in-review');
  const ready = tasks.filter((task) => dependencyState(project, task).ready);

  const policy = registry.gates.licencePolicy;
  const assets = project.assets || [];
  const badAssets = assets.filter((asset) => {
    const classification = classifyLicence(asset.licence, policy);
    return classification.verdict !== 'allowed' || !asset.verified || (classification.attributionRequired && !asset.attribution);
  });
  const measurements = project.perfMeasurements || [];
  const perfRows = (project.perfProfiles || []).map((profileId) => {
    const profile = registry.profileById.get(profileId);
    const latest = [...measurements].reverse().find((entry) => entry.profile === profileId);
    if (!latest) return { profileId, status: 'not measured', detail: profile ? `target ${profile.targetFps} fps` : '' };
    const pass = Number(latest.avgFps) >= profile.targetFps && Number(latest.p1Fps) >= profile.floorFps;
    return {
      profileId,
      status: pass ? 'pass' : 'fail',
      detail: `${latest.avgFps} fps avg / ${latest.p1Fps} fps 1% low on ${latest.device}`,
    };
  });

  const lines = [
    `# Status — ${project.title}`,
    '',
    `Updated ${new Date().toISOString()}`,
    '',
    '## Headline',
    '',
    `- Milestone: **${current ? `${current.order}. ${current.name}` : 'all phases complete'}**`,
    `- Deliverables approved: **${counts.approved} / ${tasks.length}** (${pct(counts.approved, tasks.length)})`,
    `- Awaiting review: **${counts.inReview}** · rejected: **${counts.rejected}** · blocked: **${counts.blocked}**`,
    `- Ready to start now: **${ready.length}**`,
    `- Active departments: **${project.departments.length}**`,
    '',
    '## Phase progress',
    '',
    '| Phase | Approved | Tasks | State |',
    '| --- | ---: | ---: | --- |',
    ...phases.map((phase) => `| ${phase.order}. ${phase.name} | ${phase.approved} | ${phase.tasks} | ${phase.complete ? 'complete' : phase.approved || phase.inReview ? 'in progress' : 'not started'} |`),
    '',
    '## What the Director is waiting on',
    '',
    ...(awaiting.length
      ? awaiting.map((task) => `- \`${task.id}\` ${task.name} — gate ${task.lastGate?.ok ? 'passed' : 'not passed'}, review with \`npm run studio -- review ${project.slug} ${task.id} --approve\``)
      : ['- nothing awaiting review']),
    '',
    '## Needs revision',
    '',
    ...(rejected.length
      ? rejected.map((task) => {
        const last = task.reviews?.[task.reviews.length - 1];
        return `- \`${task.id}\` ${task.name} — ${last?.note || 'no note'}`;
      })
      : ['- nothing rejected']),
    '',
    '## Blocked',
    '',
    ...(blocked.length
      ? blocked.map((task) => `- \`${task.id}\` ${task.name} — ${task.blockedReason}`)
      : ['- nothing blocked']),
    '',
    '## Departments',
    '',
    '| Department | Approved / tasks | Next ready task |',
    '| --- | ---: | --- |',
    ...project.departments.map((dept) => {
      const deptTasks = tasks.filter((task) => task.dept === dept.id);
      const approved = deptTasks.filter((task) => task.status === 'approved').length;
      const next = readyTasks(project, dept.id)[0];
      return `| ${dept.id} ${dept.name} | ${approved} / ${deptTasks.length} | ${next ? `\`${next.id}\` ${next.name}` : '—'} |`;
    }),
    '',
    '## Performance targets (measured, not claimed)',
    '',
    '| Profile | State | Measurement |',
    '| --- | --- | --- |',
    ...perfRows.map((row) => `| ${row.profileId} | ${row.status} | ${row.detail} |`),
    '',
    '## Asset licensing',
    '',
    `- ${assets.length} assets recorded, ${badAssets.length} failing the licence or verification gate.`,
    ...badAssets.slice(0, 10).map((asset) => `- ${asset.id || asset.name}: ${asset.licence || 'no licence'}${asset.verified ? '' : ' (unverified)'}`),
    '',
    '## Blocking risks',
    '',
    ...(blocked.length || badAssets.length || counts.rejected
      ? [
        blocked.length ? `- ${blocked.length} dependant task(s) blocked by an unapproved prerequisite.` : null,
        badAssets.length ? `- ${badAssets.length} asset(s) would block release until licensed or replaced.` : null,
        counts.rejected ? `- ${counts.rejected} deliverable(s) returned for revision.` : null,
      ].filter(Boolean)
      : ['- none recorded']),
    '',
  ];
  return `${lines.join('\n')}\n`;
}

export function promptMarkdown(project, dept, registry, tasks, options = {}) {
  const full = registry.byId.get(dept.id);
  const division = registry.divisionById.get(dept.division);
  const approval = options.allTasks ? tasks : tasks.filter((task) => task.status !== 'approved');
  const lines = [
    `# Department instantiation — ${dept.id} ${dept.name}`,
    '',
    `You are the **${dept.name}** department (${dept.id}) of the studio working on **${project.title}**. You are a specialist worker with your own queue, memory and deliverables. Read this whole prompt before acting, then work your queue.`,
    '',
    '## Project',
    '',
    `- Project: \`${project.slug}\` at \`studio/projects/${project.slug}/\``,
    `- Concept: ${project.concept}`,
    `- Genres: ${project.genreNames.join(', ') || 'none detected (universal pipeline)'}`,
    `- Dimension: ${project.dimension.toUpperCase()} · Platforms: ${project.platforms.join(', ')}`,
    `- Performance profiles: ${project.perfProfiles.join(', ')}`,
    `- Division: ${division?.name}`,
    '',
    '## Your charter',
    '',
    full ? charterMarkdown(full, registry).split('## System instructions')[1].split('## Mission')[0].trim() : dept.mission,
    '',
    '## Read first',
    '',
    '- `studio/projects/' + project.slug + '/SPEC.md` — the master specification',
    '- `studio/projects/' + project.slug + '/knowledge/gdd.md` — the game design',
    '- Your memory: `studio/projects/' + project.slug + '/memory/' + dept.slug + '.md`',
    ...(dept.inputs || []).map((input) => `- Input: ${input}`),
    ...(dept.consults?.length ? [`- Consult ${dept.consults.map((id) => `${id} ${registry.byId.get(id)?.name}`).join(', ')} when expertise you do not own is required.`] : []),
    '',
    '## Your assigned tasks',
    '',
    ...(approval.length
      ? approval.map((task) => [
        `### ${task.id} — ${task.name}`,
        '',
        `Phase: ${registry.phaseById.get(task.phase)?.name || task.phase} · Status: ${task.status}${task.blockedReason ? ` (blocked: ${task.blockedReason})` : ''}`,
        `Artifact: \`${task.artifact}\``,
        `Checks: ${task.checks.length ? task.checks.join(', ') : 'structural gate only'}`,
        task.dependsOn.length ? `Prerequisites: ${task.dependsOn.map((id) => `\`${id}\``).join(', ')}` : 'Prerequisites: none',
        '',
        'Acceptance criteria:',
        ...task.acceptance.map((criterion) => `- ${criterion}`),
        '',
      ].join('\n'))
      : ['All of your tasks are approved. Report completion to the Studio Director and stay available for revision requests.']),
    '## Working contract',
    '',
    '1. Work in the repository. Write the artifact at its path, using `studio/knowledge/templates/deliverable.md` as the shape (front matter with `owner`, `department`, `revision`; sections `Deliverable`, `Acceptance`, `Handoff`).',
    '2. Put real evidence in the document: file paths, commands run, measured numbers, asset ids. Never write a claim you did not verify.',
    '3. Mark yourself in progress with `npm run studio -- start ' + project.slug + ' <task-id>`, then submit with `npm run studio -- submit ' + project.slug + ' <task-id>`.',
    '4. If a named check cannot run here, submit with `--skip <check> --reason "..."`; the skip is visible to the Director and is not a pass.',
    '5. Append findings, open questions and assistance requests to your memory file. Do not edit another department\'s artifact or another department\'s memory.',
    '6. Do not implement another department\'s system. Raise a request to the Studio Director instead.',
    '',
    '## Definition of done for this session',
    '',
    '- Every ready task either submitted for review or explicitly blocked with a reason.',
    '- Your memory file updated with what you did, what you learned and what you need.',
    '- No unverified claims, no silent scope changes, no edits outside your ownership.',
    '',
  ];
  return `${lines.join('\n')}\n`;
}

export function reviewMarkdown(project, task, gate) {
  const lines = [
    `# Review — ${task.id} ${task.name}`,
    '',
    `Project: ${project.slug} · Department: ${task.dept} · Phase: ${task.phase}`,
    '',
    '## Gate result',
    '',
    `Structural: ${gate.structural.ok ? 'pass' : 'fail'} (${gate.structural.chars} chars, ${gate.structural.words} words)`,
    '',
    '| Check | Status | Detail |',
    '| --- | --- | --- |',
    ...gate.checks.map((check) => `| ${check.name} | ${check.status} | ${String(check.detail || '').replace(/\n/g, '<br>').slice(0, 400)} |`),
    '',
    '## Structural problems',
    '',
    ...(gate.structural.problems.length ? gate.structural.problems.map((problem) => `- ${problem}`) : ['- none']),
    '',
    '## Check problems',
    '',
    ...(gate.checks.flatMap((check) => (check.problems || []).map((problem) => `- ${check.name}: ${problem}`)) || ['- none']),
    '',
  ];
  return `${lines.join('\n')}\n`;
}
